export const HAPSIDA_RULE = `"-(으)ㅂ시다"는 회의 진행자가 여러 사람에게 제안할 때만 씁니다. 상사 한 사람에게는 무례하게 들릴 수 있으므로 "-(으)ㄹ까요?"를 씁니다.`;

const levelRow = (lv: Level) => {
  const s = LEVEL_SPECS[lv];
  const sent = s.maxSentences ? `, 한 번에 최대 ${s.maxSentences}문장` : '';
  return `| ${lv} | ${s.grammar} | ${s.recommended[0]}~${s.recommended[1]}어절, 최대 ${s.maxEojeol}어절${sent} | ${s.style} |`;
};

