export type Level = '초급' | '중급' | '고급';
export const LEVELS: Level[] = ['초급', '중급', '고급'];

export interface LevelSpec {
  /** 문법 범위 (교재) */
  grammar: string;
  /** 권장 어절 범위 */
  recommended: [number, number];
  /** 최대 어절 (반드시 지킴) */
  maxEojeol: number;
  /** 한 번에 쓰는 최대 문장 수 (없으면 null) */
  maxSentences: number | null;
  /** 학습자가 하는 말의 문체 */
  style: string;
}

